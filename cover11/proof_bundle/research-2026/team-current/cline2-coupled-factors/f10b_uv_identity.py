"""cline2-coupled-factors f10b: exact test of the endpoint-copy identity u_k = v_k.

A genuine inward-root diagram is generated by SOLVING the switch conditions rather than
sampling blindly: given the 9 site polar angles and 9 radii (18 unknowns), the nine
switches P_k must be unit-circle points at distance exactly r from both c_k and c_{k+1}
(18 scalar equations).  We solve that system with Newton/least-squares from random starts,
keep only converged solutions that satisfy every geometric admissibility condition
(|c_k| <= sqrt(1-r^2), switch cap, widths summing to 2pi), and then measure
    Delta_k = u_k - v_k,   u_k = |P_{k-1}-c_k|/r,  v_k = |P_k-c_k|/r.
"""
import numpy as np, math, json, sys
from pathlib import Path
from scipy.optimize import least_squares
P = Path(__file__).parent
OUT = P / 'out'
pi = math.pi
r = 0.38
rng = np.random.default_rng(11)


def switches_from_sites(c):
    """unit-circle points at distance r from consecutive sites (None if impossible)"""
    Pt = []
    for k in range(9):
        a = c[k]; b = c[(k+1) % 9]
        m = (a+b)/2; d = b-a
        nv = np.array([-d[1], d[0]]); nn = np.linalg.norm(nv)
        if nn < 1e-14:
            return None
        nv /= nn
        Bc = 2*m @ nv; Cc = m @ m-1
        disc = Bc*Bc-4*Cc
        if disc <= 0:
            return None
        cand = [m+t*nv for t in (-Bc+np.array([1.0, -1.0])*math.sqrt(disc))/2]
        good = [p for p in cand if abs(np.linalg.norm(p-a)-r) < 5e-7]
        if not good:
            return None
        Pt.append(good[0])
    return np.array(Pt)


def resid(x):
    ang = x[:9]; rad = x[9:]
    c = np.stack([rad*np.cos(ang), rad*np.sin(ang)], 1)
    rs = []
    for k in range(9):
        a = c[k]; b = c[(k+1) % 9]
        m = (a+b)/2; d = b-a
        nn = np.linalg.norm(d)
        nv = np.array([-d[1], d[0]])/nn
        Bc = 2*m @ nv; Cc = m @ m-1
        disc = Bc*Bc-4*Cc
        p = None
        if disc > 0:
            cand = [m+t*nv for t in (-Bc+np.array([1.0, -1.0])*math.sqrt(disc))/2]
            gd = [q for q in cand if abs(np.linalg.norm(q-a)-r) < 1e-6]
            p = gd[0] if gd else cand[0]
        if p is None:
            p = m+nv*0.0
        # equations: |p|=1 and ||p-a|-r|=0 and ||p-b|-r|=0 (2 independent + redundancy)
        rs += [np.linalg.norm(p)-1, np.linalg.norm(p-a)-r, np.linalg.norm(p-b)-r]
    return np.array(rs)


found = 0; worst = 0.0; best_rec = None
for trial in range(400):
    ang0 = rng.uniform(0, 2*pi, 9)
    rad0 = rng.uniform(0.5, 0.90, 9)
    sol = least_squares(resid, np.r_[ang0, rad0], method='lm', max_nfev=20000)
    x = sol.x
    ang = x[:9]; rad = x[9:]
    if np.max(np.abs(resid(x))) > 1e-9:
        continue
    if np.any(rad > math.sqrt(1-r*r)+1e-9) or np.any(rad < 0.30):
        continue
    c = np.stack([rad*np.cos(ang), rad*np.sin(ang)], 1)
    d = np.linalg.norm(c[:, None, :]-c[None, :, :], axis=2) + np.eye(9)*9
    if d.min() < 2*r*0.9:          # sites too close => not a nearest-site diagram
        continue
    Pt = switches_from_sites(c)
    if Pt is None:
        continue
    th = np.unwrap(np.arctan2(Pt[:, 1], Pt[:, 0]))
    W = np.array([(th[k]-th[(k-1) % 9]) + (2*pi if k == 0 else 0) for k in range(9)])
    if np.any(W < 0) or abs(W.sum()-2*pi) > 1e-6:
        continue
    uu = np.array([np.linalg.norm(Pt[(k-1) % 9]-c[k])/r for k in range(9)])
    vv = np.array([np.linalg.norm(Pt[k]-c[k])/r for k in range(9)])
    if np.any(uu > 1+1e-9) or np.any(vv > 1+1e-9):
        continue
    found += 1
    dv = float(np.abs(uu-vv).max())
    if dv > worst:
        worst = dv; best_rec = (c.copy(), Pt.copy(), uu.copy(), vv.copy(), W.copy())
    print(f'  solution {found}: sites ok, max|u-v| = {dv:.3e}')
    if found >= 12:
        break
print(f'\nsolutions found: {found}   worst max_k |u_k-v_k| = {worst:.3e}')
if best_rec is not None:
    print('worst case u =', np.round(best_rec[2], 10))
    print('worst case v =', np.round(best_rec[3], 10))
    print('worst case w =', np.round(best_rec[4], 10))
    np.savez(OUT/'uv_worst.npz', c=best_rec[0], Pt=best_rec[1], u=best_rec[2],
             v=best_rec[3], W=best_rec[4])
