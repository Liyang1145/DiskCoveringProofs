from mpmath import mp, mpf, sqrt, asin, pi, sin, cos

mp.dps = 30
R = mpf(19)/50
print("=== constants needed by HAD ===")
print("R = 19/50 =", R)
print("a = 1 - 2R = 1 - 38/50 =", 1-2*R, " = 6/25 ?", (1-2*R) == mpf(6)/25)
print("1 - R =", 1-R, "  1 + R =", 1+R)
print("3R - 1 =", 3*R-1, "  (bound on e)")
print()
print("=== the HAD step 'e + a <= R  =>  e <= 3r - 1' ===")
print("  e + (1-2r) <= r  <=>  e <= 3r - 1.  At r = R: e <= 7/50 =", 3*R-1)
print("  Note e + a <= R and |h| + r < 1 are DIFFERENT conditions:")
print("     e <= 3R-1 =", 3*R-1, "   vs    e < 1 - R =", 1-R)
print("  => 3R-1 = 0.14 is much stronger; that is the bound HAD uses.")
print()
print("=== does |h| + R < 1 hold for the inward-root representative? ===")
print("  If |h| >= 1-R then h would lie in ring disk i (|c_i| <= sqrt(1-r^2), |h-c_i| <= |h|+|c_i|):")
for r in ['0.38', '0.3', '0.2']:
    r = mpf(r)
    bound = 1 - r + sqrt(1 - r*r)
    print("     r=%s : |h| >= 1-r=%s and |c_i| <= sqrt(1-r^2)=%s  =>  |h-c_i| <= %s  (vs r=%s)"
          % (r, mp.nstr(1-r, 6), mp.nstr(sqrt(1-r*r), 6), mp.nstr(bound, 6), r))
print("  For r=0.38: |h|+|c_i| <= 1-0.38+0.925 = 1.545 > r, so that crude bound does NOT exclude h.")
print("  The sharp argument uses the containment D cap B(outer) c D cap B(inner): h in B(outer_i) implies")
print("  h in B(inner_i), and |h - c_i^in| <= |h - c_i^out| <= r. So h IS covered by the replaced ring disk")
print("  whenever h is covered by the original one. Hence |h| + r < 1 forces |h| < 1 - R? check:")
print("     h covered by replaced config; if |h| >= 1 - R >= 1 - r then h in the ORIGINAL ring disk i")
print("     (since |h| in [1-r, 1+r] means the disk covers h) -> then h in replaced ring disk i.")
print("     But h is a HUB centre, so h would be covered by a ring disk; combined with h in int D, that")
print("     is allowed (a hub centre may be covered). So the binding constraint is h in int D of the RING")
print("     DISKS: h in V_1 requires h covered by h_1's own disk only, i.e. |h-h_1| = 0 <= r: always true.")
print()
print("=== so which bound on e does HAD actually need? ===")
print("  HAD step: B(0,a) subset V1 => a + e <= r  =>  e <= 3r-1. This is a CONSEQUENCE of the")
print("  non-adjacency hypothesis, not an input. It uses B(0,a) subset B(h1,r), i.e. the containment")
print("  of the CORE in the HUB DISK, which needs |x - h1| <= r for |x| <= a: worst case |x| = a on")
print("  the opposite ray, giving a + e <= r. Correct.")
print()
print("=== numerical sanity: e_max = 7/50 and the hub disk reaches the core boundary ===")
e = 3*R-1
print("  e=", e, " a=", 1-2*R, " a+e =", e + (1-2*R), " vs r=R:", e + (1-2*R) <= R)
print()
print("=== t <= r <= R  =>  |c-h1|^2(1-R/t) <= 0  (the enlargement step) ===")
print("  requires R >= t and t > 0. If t = 0 the ray exits immediately (h1 on the boundary of V1),")
print("  impossible since h1 is strictly inside V1 (it is the site of its own cell, which has")
print("  nonempty interior). So t > 0.")
