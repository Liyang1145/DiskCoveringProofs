"""Independent re-enumeration of the n14 k10 dual-disk catalogue (topology-audit-cc2).

Purpose: audit interface I4/I5 of lead/K10-CATALOGUE-AUDIT.md WITHOUT importing
members/topology/gen_k10_catalogue.py.  Everything is re-derived:
  * skeletons of the hub graph on m vertices (all connected graphs, m<=4) are
    generated by brute force on all 2^(m(m-1)/2) edge sets,
  * the forced number of hub-only triangular faces h = e - m + 1 is re-derived
    (from V-E+F=1 with V=N+m, F=N+2m-2, E=2N+3m-3),
  * the hub multigraph M has edge multiplicity 2 - (#chosen hub-only triangles on it),
  * ALL Euler circuits of M are enumerated (Hierholzer, all start vertices),
  * all weak compositions of |E(M)| into N positive parts,
  * faces are built directly: outer ring faces (i,i+1,link) + inner faces,
  * validity is checked by a from-scratch simplicial-disk test: 3-distinct vertices,
    edge incidence (boundary 1 / interior 2), vertex link = cycle (hub) or path (ring),
    Euler characteristic 1 (pure combinatorics, no reference to the lead code),
  * dedup by an INDEPENDENT canonical form: minimise over the full dihedral action
    x -> +-x + sh on the N-cycle (2N elements) after canonical hub relabelling by order
    of first appearance; this is manifestly a subset of the true isomorphism group and a
    superset is not needed for completeness of representatives.

Output: JSON with raw counts per skeleton, phase1 (cheap dedup) and final (full dedup)
counts, so they can be compared with lead/catalogue-fixed.log and members/topology
stored lists.
"""
import json
import sys
import time
from collections import defaultdict
from itertools import combinations
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "evidence"
OUT.mkdir(exist_ok=True)


def ekey(a, b):
    return (a, b) if a < b else (b, a)


# ---------------------------------------------------------------- skeletons
def all_graphs(m):
    """all edge subsets of K_m, returned as sorted tuple of edges"""
    verts = list(range(m))
    pairs = list(combinations(verts, 2))
    for mask in range(1 << len(pairs)):
        es = tuple(pairs[i] for i in range(len(pairs)) if (mask >> i) & 1)
        yield es


def connected(m, edges):
    if m == 0:
        return True
    adj = defaultdict(set)
    for a, b in edges:
        adj[a].add(b)
        adj[b].add(a)
    seen = {0}
    stack = [0]
    while stack:
        v = stack.pop()
        for w in adj[v]:
            if w not in seen:
                seen.add(w)
                stack.append(w)
    return len(seen) == m


def triangles(edges):
    es = set(map(lambda e: ekey(*e), edges))
    verts = sorted(set(v for e in edges for v in e))
    out = []
    for t in combinations(verts, 3):
        if all(ekey(a, b) in es for a, b in combinations(t, 2)):
            out.append(t)
    return out


# ---------------------------------------------------------------- Euler circuits
def euler_circuits(multi, start):
    """multi: dict edge->multiplicity.  Returns list of vertex paths (len S+1, closed)."""
    inst = []
    for e, c in multi.items():
        for _ in range(c):
            inst.append(e)
    S = len(inst)
    adj = defaultdict(list)
    for idx, (a, b) in enumerate(inst):
        adj[a].append(idx)
        adj[b].append(idx)
    seen = set()
    out = []

    def rec(v, used, path):
        if len(path) == S + 1:
            if v == start:
                t = tuple(path)
                if t not in seen:
                    seen.add(t)
                    out.append(list(path))
            return
        for idx in adj[v]:
            if idx in used:
                continue
            a, b = inst[idx]
            w = b if a == v else a
            used.add(idx)
            path.append(w)
            rec(w, used, path)
            path.pop()
            used.remove(idx)

    if S == 0:
        return [[]]
    rec(start, set(), [start])
    return out


def comps_pos(total, parts):
    """weak compositions of total into parts nonneg ints (generator style: 0 allowed)"""
    if parts == 1:
        yield (total,)
        return
    for first in range(total + 1):
        for rest in comps_pos(total - first, parts - 1):
            yield (first,) + rest


# ---------------------------------------------------------------- disk validity
def is_disk_complex(N, m, faces):
    """From-scratch combinatorial disk test (independent of lead code)."""
    fs = [tuple(sorted(f)) for f in faces]
    for f in fs:
        if len(set(f)) != 3:
            return False
        if sum(1 for v in f if v < N) > 2:
            return False
        if sum(1 for v in f if v < N) == 2:
            a, b = [v for v in f if v < N]
            if (a - b) % N not in (1, N - 1):
                return False
    cnt = defaultdict(int)
    for f in fs:
        for a, b in combinations(f, 2):
            cnt[ekey(a, b)] += 1
    # every edge incidence 2, except N ring-ring edges incidence 1
    ring_edges = set(ekey(i, (i + 1) % N) for i in range(N))
    for e, c in cnt.items():
        want = 1 if e in ring_edges else 2
        if c != want:
            return False
    if len(ring_edges) != N:
        return False
    # Euler characteristic of the resulting 2-complex
    V = N + m
    E = len(cnt)
    F = len(fs)
    if V - E + F != 1:
        return False
    # vertex links
    at = defaultdict(list)
    for i, f in enumerate(fs):
        for v in f:
            at[v].append(i)
    for v in range(V):
        nb = defaultdict(set)
        for i in at[v]:
            o = [x for x in fs[i] if x != v]
            nb[o[0]].add(o[1])
            nb[o[1]].add(o[0])
        # each vertex must have a connected link
        if not nb:
            return False
        start = next(iter(nb))
        seen = {start}
        stack = [start]
        while stack:
            x = stack.pop()
            for y in nb[x]:
                if y not in seen:
                    seen.add(y)
                    stack.append(y)
        if len(seen) != len(nb):
            return False
        if v >= N:
            # hub: every link vertex degree exactly 2 (cycle)
            for x, ys in nb.items():
                if len(ys) != 2:
                    return False
        else:
            # ring: link is a path with exactly two degree-1 ends
            ends = [x for x in nb if len(nb[x]) == 1]
            if len(nb) > 1 and len(ends) != 2:
                return False
    return True


# ---------------------------------------------------------------- canonical form
def canon_cheap(N, faces):
    """independent cheap canonical form: only ring shifts + reflections of the form
    x -> 2s - x plus x -> 2s+1-x (all N odd-reflections) to match the FULL dihedral
    group exactly; hubs untouched."""
    best = None
    for sh in range(N):
        for eps in (1, -1):
            img = []
            for f in faces:
                out = []
                for v in f:
                    if v < N:
                        out.append((eps * v + sh) % N)
                    else:
                        out.append(v)
                img.append(tuple(sorted(out)))
            key = tuple(sorted(img))
            if best is None or key < best:
                best = key
    return best


def canon_full_indep(N, faces):
    """independent full canonical form.
    Step 1: canonical hub relabelling by order of first appearance in the sorted face
    tuple (invariant under every hub permutation, independent of the lead's
    first-appearance-in-range rule).  Step 2: minimise over the true dihedral action
    x -> eps*x + sh, eps in {+1,-1}."""
    hub_ids = sorted(set(v for f in faces for v in f if v >= N))
    remap = {h: N + i for i, h in enumerate(hub_ids)}
    relab = [tuple(sorted(remap.get(v, v) for v in f)) for f in faces]
    base = tuple(sorted(relab))
    best = None
    for sh in range(N):
        for eps in (1, -1):
            img = []
            for f in base:
                out = []
                for v in f:
                    if v < N:
                        out.append((eps * v + sh) % N)
                    else:
                        out.append(v)
                img.append(tuple(sorted(out)))
            key = tuple(sorted(img))
            if best is None or key < best:
                best = key
    return best


# ---------------------------------------------------------------- main enumeration
def enumerate_NM(N, m, budget_s=900.0):
    t0 = time.time()
    per_skel = {}
    phase1 = {}
    classes = set()
    total_raw = 0
    for edges in all_graphs(m):
        if m >= 2 and not connected(m, edges):
            continue
        e = len(edges)
        h = e - m + 1          # forced number of hub-only triangles
        if h < 0:
            continue
        tris = triangles(edges)
        if h > len(tris):
            continue
        for sel in combinations(range(len(tris)), h):
            hull = [tris[i] for i in sel]
            te = defaultdict(int)
            for t in hull:
                for a, b in combinations(t, 2):
                    te[ekey(a, b)] += 1
            multi = {}
            ok = True
            for a, b in edges:
                c = 2 - te[ekey(a, b)]
                if c < 0:
                    ok = False
                    break
                if c:
                    multi[(a, b)] = c
            if not ok:
                continue
            S = sum(multi.values())
            starts = sorted(set(v for ed in multi for v in ed)) if multi else [0]
            for st in starts:
                for walk in euler_circuits(multi, st):
                    if time.time() - t0 > budget_s:
                        raise TimeoutError("budget")
                    for cuts in comps_pos(S, N):
                        stpos = [0]
                        for L in cuts:
                            stpos.append(stpos[-1] + L)
                        segs = [walk[stpos[i]:stpos[i + 1] + 1] for i in range(N)]
                        if any(len(set(s)) != len(s) for s in segs):
                            continue
                        link = [walk[stpos[i + 1]] for i in range(N)]
                        faces = [(i, (i + 1) % N, N + link[i]) for i in range(N)]
                        for i in range(N):
                            for k in range(stpos[i], stpos[i + 1]):
                                faces.append((i, N + walk[k], N + walk[k + 1]))
                        for t in hull:
                            faces.append((N + t[0], N + t[1], N + t[2]))
                        if not is_disk_complex(N, m, faces):
                            continue
                        total_raw += 1
                        per_skel[tuple(sorted(edges))] = per_skel.get(
                            tuple(sorted(edges)), 0) + 1
                        ck = canon_cheap(N, faces)
                        if ck not in phase1:
                            phase1[ck] = [tuple(sorted(f)) for f in faces]
    classes = set(canon_full_indep(N, faces) for faces in phase1.values())
    return dict(raw=total_raw, per_skel={str(k): v for k, v in per_skel.items()},
                phase1_cheap=len(phase1), full_classes=len(classes),
                classes=[json.dumps(list(c)) for c in sorted(classes)],
                runtime=time.time() - t0)


if __name__ == "__main__":
    N = int(sys.argv[1]) if len(sys.argv) > 1 else 10
    m = int(sys.argv[2]) if len(sys.argv) > 2 else 3
    r = enumerate_NM(N, m)
    summary = {k: v for k, v in r.items() if k != "classes"}
    print(json.dumps(summary, indent=1))
    (OUT / ("indep-enum-N%d-m%d.json" % (N, m))).write_text(
        json.dumps(r, indent=1), encoding="utf-8")
    print("classes ->", OUT / ("indep-enum-N%d-m%d.json" % (N, m)))
