"""Generate core-Lean replay modules from parsed WIP data (c450.json):
  DCPN11Core/C450Replay/SegK/Data.lean     segment + c450Segs entry + head checks
  DCPN11Core/C450Replay/SegK/CellsJ.lean   8 cells per chunk, each `cellNN_ok : cellB seg cellNN = true`
  DCPN11Core/C450Replay/SegK/All.lean      all 32 cells pass + Qcell tiling of [-1,1] + packet count."""
import json,sys,os
from fractions import Fraction as F
D=json.load(open(sys.argv[1])); out=sys.argv[2]; ks=[int(x) for x in sys.argv[3:]]
def r(x):
    x=F(x)
    return f"({x.numerator}:Rat)" if x.denominator==1 else f"(({x.numerator}:Rat)/{x.denominator})"
def seg(v): return "⟨"+",".join(r(x) for x in v)+"⟩"
def w(fn,L):
    os.makedirs(os.path.dirname(fn),exist_ok=True); tmp=fn+".tmp"
    open(tmp,'w').write("\n".join(L)+"\n"); os.replace(tmp,fn)
HDR=lambda k,what:[f"/- GENERATED by c450-replay/gen_lean.py from WIP snapshot n11-wip-0001 ({what}). -/"]
for k in ks:
    v=D['segs'][str(k)]; ns=f"DCPN11Core.C450Replay.Seg{k}"; base=os.path.join(out,f"Seg{k}")
    w(base+"/Data.lean",HDR(k,f"C450Source{k}Data.lean, DSHTenBoundaryData.c450Segs[{k-1}]")+[
      "import DCPN11Core.C450Replay.Kernel",f"namespace {ns}","open DCPN11Core.C450Replay",
      f"def seg : TenSeg := {seg(v['seg'])}",
      f"/-- entry {k-1} (0-based) of the WIP `c450Segs`, transcribed from DSHTenBoundaryData.lean. -/",
      f"def listed : TenSeg := {seg(D['c450Segs'][k-1])}",
      "theorem head_ok : segHeadB seg = true := by decide +kernel",
      "theorem listed_ok : seg.beq listed = true := by decide +kernel",f"end {ns}"])
    cells=v['cells']
    BUD=int(os.environ.get('PKT_BUDGET','0'))
    if BUD:
        chunks=[];cur=[];n=0
        for i,c in enumerate(cells):
            if cur and n+len(c['packets'])>BUD: chunks.append(cur);cur=[];n=0
            cur.append(i);n+=len(c['packets'])
        chunks.append(cur)
    else:
        chunks=[range(i,min(i+8,len(cells))) for i in range(0,len(cells),8)]
    for j,ch in enumerate(chunks):
        L=HDR(k,f"C450Source{k}GroupedC{ch[0]+1:02d}..{ch[-1]+1:02d}.lean")+[f"import DCPN11Core.C450Replay.Seg{k}.Data",f"namespace {ns}","open DCPN11Core.C450Replay"]
        for ci in ch:
            c=cells[ci]
            L.append(f"def cell{ci+1:02d} : Cell := ⟨⟨{r(c['q'][0])},{r(c['q'][1])}⟩,[")
            L.append(",\n".join("  ⟨"+",".join(r(x) for x in p)+"⟩" for p in c['packets'])+"]⟩")
            L.append(f"theorem cell{ci+1:02d}_ok : cellB seg cell{ci+1:02d} = true := by decide +kernel")
        L.append(f"end {ns}"); w(base+f"/Cells{j+1}.lean",L)
    names=[f"cell{ci+1:02d}" for ci in range(len(cells))]
    w(base+"/All.lean",HDR(k,"assembly")+[f"import DCPN11Core.C450Replay.Seg{k}.Cells{j+1}" for j in range(len(chunks))]+[
      f"namespace {ns}","open DCPN11Core.C450Replay",
      f"def cells : List Cell := [{','.join(names)}]",
      "theorem tiling_ok : tileB (-1) 1 (cells.map Cell.q) = true := by decide +kernel",
      "theorem count_ok : (cells.map (fun c => c.packets.length)).foldl (·+·) 0 = %d := by decide +kernel"%sum(len(c['packets']) for c in cells),
      "theorem all_ok : cells.all (cellB seg) = true := by",
      "  simp only [cells, List.all_cons, List.all_nil, Bool.and_true, "+", ".join(n+"_ok" for n in names)+"]",
      "/-- Every packet of every cell satisfies the field-for-field restatement of WIP `Valid`. -/",
      "theorem all_valid : ∀ c ∈ cells, ∀ p ∈ c.packets, ValidQ seg p ∧ p.qLo = c.q.lo ∧ p.qHi = c.q.hi := by",
      "  intro c hc",
      "  have h := List.all_eq_true.mp all_ok c hc",
      "  exact cellB_packet h",
      f"end {ns}"])
    print(k,len(chunks))
