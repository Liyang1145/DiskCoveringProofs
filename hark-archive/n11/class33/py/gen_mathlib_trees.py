"""Emit WIP-style (Mathlib) DRAFT switch-tree modules for rep1 (q1Faces 1 4) and q0m2 (q0Faces 2), in the exact
shape of the A25-green SharedMomentConcreteSwitchBatch (direct leaves, switchCell_split, norm_num leaf proofs),
plus Class33SwitchFields.lean: the `switches` fields (coefficient identities + SwitchCertificates) and maxima.
UNCOMPILED here. Leaves pre-validated exactly (py/switch_kernel.py; core Lean Class33Core.SwTrees.*)."""
import json, sys, os
from fractions import Fraction as F
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'lean' / 'N11Formalization'
def q(x): x = F(x); return f'({x.numerator}/{x.denominator} : ℚ)' if x.denominator != 1 else f'({x.numerator} : ℚ)'
def wr(p, s):
    t = str(p) + '.tmp'; Path(t).write_text(s); os.replace(t, p)
def code(e): return sum(2 ** i for i in e)
NORM = 'switchCell,switchDirectUpperQ,switchQuadraticCell,switchLinearCell,RatInterval.ofRat,RatInterval.mul,RatInterval.add,RationalTrigCellBounds.sinCell,RationalTrigCellBounds.squareCell,RationalTrigCellBounds.midpoint,RationalTrigCellBounds.halfWidth,sinLoNLag,sinHiNLag,sinTQ,CompactQuadraticMomentMaximum.maximumQ,Finset.sum_range_succ'
TABS = [('rep1', 'Rep1', 'q1Faces 1 4'), ('q0m2', 'Q0M2', 'q0Faces 2')]
for tab, Mod, FS in TABS:
    d = json.loads((ROOT / 'data' / f'switch_trees_{tab}.json').read_text())
    for j in range(9):
        r = d[str(j)]; c = r['coeff']; leaves = {(F(a), F(b)) for a, b in r['leaves']}
        ns = f'N11Formalization.Class33SwitchTree{Mod}S{j}'
        pre = 'sw'
        names = f'{pre}_leaf,{pre}_p,{pre}_q,{pre}_b,{pre}_d2,{pre}_d1,{pre}_bound,' + NORM
        out = [f'import N11Formalization.SharedMomentConcreteLeafControls', '',
               f'/-! Class33 DRAFT (uncompiled): {tab} canonical switch {j} ({FS}), direct-leaf tree, {len(leaves)} leaves.',
               f'Generated by class33/py/gen_switch_trees.py + gen_mathlib_trees.py; every leaf pre-validated exactly. -/',
               'set_option autoImplicit false', 'noncomputable section', f'namespace {ns}',
               'open RationalBoxSubdivision SharedMomentFactorIntervalCertificate',
               'open SharedMomentFactorGridCertificate SharedMomentConcreteLeafControls', '']
        for x in ['p', 'q', 'b', 'd2', 'd1']:
            out.append(f'def {pre}_{x} : ℚ := {q(c[x])}')
        out.append(f'def {pre}_bound : ℚ := {q(r["M"])}')
        out.append(f'def {pre}_leaf (B : Cell (Fin 1)) : Prop :=\n  switchDirectUpperQ {pre}_p {pre}_q {pre}_b {pre}_d2 {pre}_d1 B ≤ {pre}_bound\n')
        cnt = [0]
        def rec(lo, hi):
            if (lo, hi) in leaves:
                n = cnt[0]; cnt[0] += 1
                out.append(f'theorem node_{n} : Certificate {pre}_leaf\n    (switchCell {q(lo)} {q(hi)}) := by\n  apply Certificate.accept\n  norm_num [{names}]\n')
                return n
            m = (lo + hi) / 2
            a = rec(lo, m); b = rec(m, hi)
            n = cnt[0]; cnt[0] += 1
            out.append(f'theorem node_{n} : Certificate {pre}_leaf\n    (switchCell {q(lo)} {q(hi)}) := by\n  exact switchCell_split {q(lo)} {q(m)} {q(hi)}\n    (by norm_num) (by norm_num) node_{a} node_{b}\n')
            return n
        root = rec(F(0), F(1571, 1000))
        out.append(f'theorem root : Certificate {pre}_leaf (switchCell 0 (1571/1000 : ℚ)) := node_{root}\n')
        out.append(f'end {ns}')
        out.append(f'#print axioms {ns}.root')
        wr(OUT / f'Class33SwitchTree{Mod}S{j}.lean', '\n'.join(out) + '\n')
# ---- fields module
sys.path.insert(0, str(Path(__file__).parent)); import rep_tables as RT
f = ['import N11Formalization.Class33SwitchBridge']
for tab, Mod, FS in TABS:
    f += [f'import N11Formalization.Class33SwitchTree{Mod}S{j}' for j in range(9)]
f += ['', '/-! Class33 DRAFT (uncompiled): `switches` fields and switch maxima for rep1 and q0m2. -/',
      'set_option autoImplicit false', 'noncomputable section', 'namespace N11Formalization.Class33SwitchFields',
      'open RationalBoxSubdivision SharedMomentFiniteFactorCertificate ActualCanonicalMomentTransport',
      'open ActualEdgeFlagSums Class33RepData Class33SwitchBridge ActualRingDirectionOrder ActualRingLinkBoundaryData', '']
for tab, Mod, FS in TABS:
    d = json.loads((ROOT / 'data' / f'switch_trees_{tab}.json').read_text())
    f.append(f'def {tab}SwitchMaxN : ℕ → ℚ')
    for j in range(9): f.append(f'  | {j} => {q(d[str(j)]["M"])}')
    f.append('  | _ => 0')
    f.append(f'def {tab}SwitchMax (i : Fin 9) : ℚ := {tab}SwitchMaxN i.val')
    tot = sum(F(d[str(j)]['M']) for j in range(9))
    f.append(f'''theorem {tab}_switch_aggregate : (∑ i : Fin 9, {tab}SwitchMax i) = {q(tot)} := by
  rw [Fin.sum_univ_eq_sum_range (fun n => {tab}SwitchMaxN n) 9]
  simp only [Finset.sum_range_succ,Finset.sum_range_zero,{tab}SwitchMaxN]
  norm_num
''')
    for j in range(9):
        T = f'N11Formalization.Class33SwitchTree{Mod}S{j}'
        e = sorted([j, (j + 1) % 9]); cd = code(e)
        nm = ','.join(f'{T}.sw_{x}' for x in ['p', 'q', 'b', 'd2', 'd1'])
        f.append(f'''theorem {tab}_switch{j}_eq :
    canonicalSwitchP {tab}D {tab}Kap {j}={T}.sw_p ∧ canonicalSwitchQ {tab}D {j}={T}.sw_q ∧
    canonicalSwitchB {tab}D {j}={T}.sw_b ∧ canonicalSwitchD2 {tab}D {j}={T}.sw_d2 ∧
    canonicalSwitchD1 {tab}D {j}={T}.sw_d1 := by
  have hc : cycleEdge {j} = ({{({j} : Fin 11),({(j + 1) % 9} : Fin 11)}} : Finset (Fin 11)) := by decide
  have hcode : edgeCode ({{({j} : Fin 11),({(j + 1) % 9} : Fin 11)}} : Finset (Fin 11)) = {cd} := by decide
  have hpred : ((({j} : Fin 9) - 1 : Fin 9) : ℕ) = {(j - 1) % 9} := by decide
  have hj : (({j} : Fin 9) : ℕ) = {j} := rfl
  have hne : ({j} : Fin 11) ≠ ({(j + 1) % 9} : Fin 11) := by decide
  refine ⟨?_,?_,?_,?_,?_⟩ <;>
    simp only [canonicalSwitchP,canonicalSwitchQ,canonicalSwitchB,canonicalSwitchD2,canonicalSwitchD1,
      {tab}D,{tab}Kap,hc,hcode,hpred,hj,Finset.sum_pair hne] <;>
    norm_num [{tab}MuN,{tab}SideFirstCode,{tab}SideSecondCode,{tab}KapCode,{tab}LeftFirstN,{tab}LeftSecondN,
      {tab}RightFirstN,{tab}RightSecondN,{nm}]
''')
    f.append(f'''def {tab}Switches : ∀ i : Fin 9, SwitchCertificate (canonicalSwitchP {tab}D {tab}Kap i)
    (canonicalSwitchQ {tab}D i) (canonicalSwitchB {tab}D i) (canonicalSwitchD2 {tab}D i)
    (canonicalSwitchD1 {tab}D i) ({tab}SwitchMax i) := by
  intro i
  fin_cases i''')
    for j in range(9):
        T = f'N11Formalization.Class33SwitchTree{Mod}S{j}'
        f.append(f'''  · obtain ⟨h1,h2,h3,h4,h5⟩ := {tab}_switch{j}_eq
    have hm : {tab}SwitchMax ({j} : Fin 9) = {T}.sw_bound := by
      simp [{tab}SwitchMax,{tab}SwitchMaxN,{T}.sw_bound]
    simp only [Fin.isValue] at h1 h2 h3 h4 h5 ⊢
    rw [h1,h2,h3,h4,h5,hm]
    exact switchCertificate_of_direct {T}.root''')
    f.append('')
f.append('end N11Formalization.Class33SwitchFields')
for tab, _, _ in TABS:
    f += [f'#print axioms N11Formalization.Class33SwitchFields.{tab}Switches', f'#print axioms N11Formalization.Class33SwitchFields.{tab}_switch_aggregate']
wr(OUT / 'Class33SwitchFields.lean', '\n'.join(f) + '\n')
print('ok')
