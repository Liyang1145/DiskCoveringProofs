def agg_module(name, subs):
    ns = 'N11Formalization.' + name; k = len(subs)
    L = ['import N11Formalization.' + s for s in subs]
    L += ['/-! Generated aggregation (NOT compiled, NOT paid). -/', 'set_option autoImplicit false',
          'namespace ' + ns, 'open Finset', 'noncomputable section', 'set_option maxRecDepth 10000']
    def nest(xs): return xs[0] if len(xs) == 1 else '%s ∪ (%s)' % (xs[0], nest(xs[1:]))
    ids = ['%s.newIDs' % s for s in subs]
    L.append('def newIDs : Finset (Fin 5011) := ' + nest(ids))
    disj = ' ∨ '.join('n ∈ %s' % x for x in ids)
    pat = ' | '.join(['hn'] * k)
    L += ['theorem new_terminal (n : Fin 5011) (hn : n ∈ newIDs) :', '    (DBMSourceTree.data n).terminal = true := by']
    if k == 1:
        L += ['  exact %s.new_terminal n hn' % subs[0]]
    else:
        L += ['  have hm : %s := by' % disj, '    simpa only [newIDs, Finset.mem_union] using hn', '  rcases hm with ' + pat]
        L += ['  · exact %s.new_terminal n hn' % s for s in subs]
    L += ['theorem new_radius (n : Fin 5011) (hn : n ∈ newIDs)'] + SIG
    if k == 1:
        L += ['  exact %s.new_radius n hn y hy0 hy1 hc C Z r hf' % subs[0]]
    else:
        L += ['  have hm : %s := by' % disj, '    simpa only [newIDs, Finset.mem_union] using hn', '  rcases hm with ' + pat]
        L += ['  · exact %s.new_radius n hn y hy0 hy1 hc C Z r hf' % s for s in subs]
    L += ['end', 'end ' + ns, '#print axioms %s.new_radius' % ns]
    return '\n'.join(L) + '\n'

