"""Emit WIP-format Lean modules (Paid16GeneralG03 template) for single-cell passes.
Output: energy/lean-wip/N11Formalization/Paid16GeneralHxxx.lean (21 cases each),
        Paid16GeneralHAggK.lean (<=10 groups each), Paid16GeneralHAll.lean,
        EnergyTerminalBatchB12.lean (paidIDs + bridge B12.Remaining -> B11.Remaining).
NOT compiled here (no Mathlib toolchain on this machine)."""
import os, json, sys, hashlib
from fractions import Fraction as F
HERE = os.path.dirname(os.path.abspath(__file__))
OUTD = os.path.join(HERE, 'lean-wip', 'N11Formalization'); os.makedirs(OUTD, exist_ok=True)

def q(x):
    if isinstance(x, str):
        a, b = x.split('/'); x = F(int(a), int(b))
    if x.denominator == 1: return '(%d : ℚ)' % x.numerator
    return '((%d : ℚ)/%d)' % (x.numerator, x.denominator)

def packet_lit(p):
    beta = ','.join(q(b) for b in p['beta'])
    lines = ','.join('⟨%s,%s,%s,%s,%s,%s,(%d : ℤ),.%s⟩' % (q(l['a']), q(l['b']), q(l['s']), q(l['c']), q(l['t']), q(l['e']), l['shift'], l['rule']) for l in p['line'])
    rf = ','.join(str(x) for x in p['rowFrom']); rt = ','.join(str(x) for x in p['rowTo'])
    lam = ','.join(q(x) for x in p['lam'])
    return '⟨%d,![%s],![%s],![%s],![%s],![%s],%s⟩' % (p['nodeID'], beta, lines, rf, rt, lam, q(p['rmin']))

def atomic(path, text):
    tmp = path + '.tmp'; open(tmp, 'w', encoding='utf-8').write(text); os.replace(tmp, path)

def group_module(name, pks):
    N = len(pks); ns = 'N11Formalization.' + name
    L = ['import N11Formalization.Paid16CellCertificate',
         '/-! Generated by energy/emit_lean.py (n11 energy line, 2026-10-15). %d OWN-cell packets.' % N,
         'Exact-Fraction pre-validated only; NOT compiled, NOT paid. -/',
         'set_option autoImplicit false', 'namespace ' + ns, 'open Finset Paid16CellCertificate',
         'noncomputable section', 'set_option maxRecDepth 10000', 'abbrev Case := Fin %d' % N,
         'def nodeID : Case → Fin 5011 := ![%s]' % ','.join(str(p['nodeID']) for p in pks)]
    for i, p in enumerate(pks):
        L.append('def packet%d : Packet := %s' % (i, packet_lit(p)))
        L.append('theorem valid%d : Valid packet%d := by' % (i, i))
        L.append('  constructor <;> decide +kernel')
    L.append('def packet : Case → Packet := ![%s]' % ','.join('packet%d' % i for i in range(N)))
    L.append('theorem all_valid (i : Case) : Valid (packet i) := by')
    L.append('  fin_cases i')
    for i in range(N): L.append('  · exact valid%d' % i)
    L += ['theorem node_binding (i : Case) : (packet i).nodeID = nodeID i := by',
          '  fin_cases i <;> rfl',
          'theorem terminal (i : Case) : (DBMSourceTree.data (nodeID i)).terminal = true := by',
          '  simpa only [node_binding] using (all_valid i).terminal',
          'theorem common_chart_radius (i : Case) (y : Fin 9 → ℝ)',
          '    (hy0 : ∀ q, 0 ≤ y q) (hy1 : ∑ q, y q = 1)',
          '    (hc : FlashLeafSplit.Cell (DBMTreeKernel.matrix DBMSourceTree.data 4096 (nodeID i))',
          '      (FlashLeafSplit.tlift y)) (C Z : Fin 11 → Point) (r : ℝ)',
          '    (hf : ResumeNetwork.Feasible (SourceChartIsometry.chartAnchors y) C Z r) :',
          '    SourceExactRoot.sourceRadius < r :=',
          '  Paid16CellCertificate.common_chart_radius (packet i) (all_valid i) y hy0 hy1',
          '    (by simpa only [node_binding] using hc) C Z r hf',
          'def newIDs : Finset (Fin 5011) := univ.image nodeID',
          'theorem new_count : newIDs.card = %d := by decide +kernel' % N,
          'theorem node_injective : Function.Injective nodeID := by',
          '  unfold Function.Injective', '  decide +kernel',
          'theorem new_terminal (n : Fin 5011) (hn : n ∈ newIDs) :',
          '    (DBMSourceTree.data n).terminal = true := by',
          '  obtain ⟨i, _, rfl⟩ := Finset.mem_image.mp hn', '  exact terminal i',
          'theorem new_radius (n : Fin 5011) (hn : n ∈ newIDs)',
          '    (y : Fin 9 → ℝ) (hy0 : ∀ q, 0 ≤ y q) (hy1 : ∑ q, y q = 1)',
          '    (hc : FlashLeafSplit.Cell (DBMTreeKernel.matrix DBMSourceTree.data 4096 n)',
          '      (FlashLeafSplit.tlift y)) (C Z : Fin 11 → Point) (r : ℝ)',
          '    (hf : ResumeNetwork.Feasible (SourceChartIsometry.chartAnchors y) C Z r) :',
          '    SourceExactRoot.sourceRadius < r := by',
          '  obtain ⟨i, _, rfl⟩ := Finset.mem_image.mp hn',
          '  exact common_chart_radius i y hy0 hy1 hc C Z r hf',
          'end', 'end ' + ns,
          '#print axioms %s.all_valid' % ns, '#print axioms %s.new_radius' % ns]
    return '\n'.join(L) + '\n'

