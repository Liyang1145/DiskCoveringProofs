if __name__ == '__main__':
    certs = os.path.join(HERE, 'certs')
    pks = []
    for f in sorted(os.listdir(certs), key=lambda s: int(s.split('.')[0])):
        r = json.load(open(os.path.join(certs, f)))
        if r['status'] == 'pass': pks.append(r['packet'])
    groups = [pks[i:i + 21] for i in range(0, len(pks), 21)]
    names = []
    manifest = []
    for gi, g in enumerate(groups):
        nm = 'Paid16GeneralH%03d' % (gi + 1); names.append(nm)
        txt = group_module(nm, g); p = os.path.join(OUTD, nm + '.lean'); atomic(p, txt)
        manifest.append(dict(module=nm, cases=len(g), nodes=[x['nodeID'] for x in g], sha256=hashlib.sha256(txt.encode()).hexdigest(), bytes=len(txt.encode())))
    aggs = []
    for ai in range(0, len(names), 10):
        nm = 'Paid16GeneralHAgg%02d' % (ai // 10 + 1); aggs.append(nm)
        txt = agg_module(nm, names[ai:ai + 10]); atomic(os.path.join(OUTD, nm + '.lean'), txt)
        manifest.append(dict(module=nm, subs=names[ai:ai + 10], sha256=hashlib.sha256(txt.encode()).hexdigest()))
    txt = agg_module('Paid16GeneralHAll', aggs); atomic(os.path.join(OUTD, 'Paid16GeneralHAll.lean'), txt)
    manifest.append(dict(module='Paid16GeneralHAll', subs=aggs, sha256=hashlib.sha256(txt.encode()).hexdigest()))
    atomic(os.path.join(OUTD, 'EnergyTerminalBatchB12.lean'), B12)
    manifest.append(dict(module='EnergyTerminalBatchB12', sha256=hashlib.sha256(B12.encode()).hexdigest()))
    atomic(os.path.join(HERE, 'lean-wip', 'MANIFEST.json'), json.dumps(dict(packets=len(pks), groups=len(groups), modules=manifest), indent=1))
