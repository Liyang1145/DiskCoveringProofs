#!/usr/bin/env python3
"""Emit DRAFT WIP-style Lean for refinement (split) certificates in split/<node>.json.
Per node: EnergyRefineNxxxx.lean = local DBMTreeKernel tree (preorder ids, scale 4096*2^8),
leaf MPackets (Paid16MatrixCellCertificate), decide +kernel validity, node_radius.
Aggregation: EnergyRefineAggK / EnergyRefineAll; EnergyTerminalBatchB13 (bridge B13 -> B12).
Also re-checks every leaf exactly (split.check_matrix) and the split rule, before emitting."""
import os, sys, json, hashlib
from fractions import Fraction as F
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
OUTD = os.path.join(HERE, 'lean-wip', 'N11Formalization')
from emit_lean import q, atomic, agg_module, SIG
import split as SP

def dec(x):
    if isinstance(x, str) and '/' in x:
        a, b = x.split('/'); return F(int(a), int(b))
    if isinstance(x, dict): return {k: dec(v) for k, v in x.items()}
    if isinstance(x, list): return [dec(v) for v in x]
    return x

def flatten(tr):
    """preorder list of dicts: D, terminal, split(i,j,m), left, right, packet"""
    out = []
    def go(t):
        idx = len(out); out.append(None)
        if t['kind'] == 'leaf':
            out[idx] = dict(D=t['D'], terminal=True, packet=dec(t['packet']))
        else:
            i, j, m = t['split']
            l = go(t['left']); r = go(t['right'])
            out[idx] = dict(D=t['D'], terminal=False, i=i, j=j, m=m, left=l, right=r)
        return idx
    go(tr); return out

def check_tree(nodes, n0D):
    # root = 256 * source db; split rule exact (child == kernel min rule, implies Valid); leaves exact-valid
    assert nodes[0]['D'] == n0D
    for k, nd in enumerate(nodes):
        if nd['terminal']:
            ok, res = SP.check_matrix(nd['D'], nd['packet']); assert ok, (k, res)
        else:
            L, R = SP.split_child(nd['D'], nd['i'], nd['j'], nd['m'])
            assert nodes[nd['left']]['D'] == L and nodes[nd['right']]['D'] == R and nd['left'] > k and nd['right'] > k

def mat(D): return '![%s]' % ','.join('![%s]' % ','.join(str(x) for x in r) for r in D)

def line(l): return '⟨%s,%s,%s,%s,%s,%s,(%d : ℤ),.%s⟩' % (q(l['a']), q(l['b']), q(l['s']), q(l['c']), q(l['t']), q(l['e']), l['shift'], l['rule'])

def module(n, nodes):
    K = len(nodes); ns = 'N11Formalization.EnergyRefineN%04d' % n
    L = ['import N11Formalization.Paid16MatrixCellCertificate',
         '/-! DRAFT generated by energy/emit_split.py: refinement of source terminal %d into %d leaves.' % (n, sum(x['terminal'] for x in nodes)),
         'Exact-Fraction pre-validated; NOT compiled, NOT paid. -/',
         'set_option autoImplicit false', 'namespace ' + ns, 'open Finset Paid16MatrixCellCertificate DBMTreeKernel',
         'noncomputable section', 'set_option maxRecDepth 100000', 'abbrev K := %d' % K]
    for k, nd in enumerate(nodes):
        if nd['terminal']:
            L.append('def node%d : Node K := ⟨%s,true,0,0,0,0,0⟩' % (k, mat(nd['D'])))
        else:
            L.append('def node%d : Node K := ⟨%s,false,%d,%d,%d,%d,%d⟩' % (k, mat(nd['D']), nd['i'], nd['j'], nd['m'], nd['left'], nd['right']))
    L.append('def sub : Fin K → Node K := ![%s]' % ','.join('node%d' % k for k in range(K)))
    L.append('theorem sub_valid : ∀ l, Valid sub l := by decide +kernel')
    L.append('theorem root_scaled : ∀ a b, (sub 0).db a b = 256 * (DBMSourceTree.data %d).db a b := by decide +kernel' % n)
    leaves = [k for k in range(K) if nodes[k]['terminal']]
    for k in leaves:
        p = nodes[k]['packet']
        L.append('def pk%d : MPacket := ⟨node%d.db,1048576,![%s],![%s],![%s],![%s],![%s],%s⟩' % (
            k, k, ','.join(q(b) for b in p['beta']), ','.join(line(l) for l in p['line']),
            ','.join(map(str, p['rowFrom'])), ','.join(map(str, p['rowTo'])), ','.join(q(x) for x in p['lam']), q(p['rmin'])))
        L.append('theorem valid%d : MValid pk%d := by' % (k, k))
        L.append('  constructor <;> decide +kernel')
    dflt = 'pk%d' % leaves[0]
    L.append('def pk : Fin K → MPacket := ![%s]' % ','.join(('pk%d' % k) if nodes[k]['terminal'] else dflt for k in range(K)))
    L.append('theorem pk_ok : ∀ l, (sub l).terminal = true → MValid (pk l) ∧ (pk l).D = (sub l).db ∧ (pk l).S = 1048576 := by')
    L.append('  intro l hl')
    L.append('  fin_cases l <;> simp_all [sub, pk] <;> first | exact ⟨by assumption, rfl, rfl⟩ | (refine ⟨?_, rfl, rfl⟩; first %s)' % ' | '.join('exact valid%d' % k for k in leaves))
    L += ['theorem terminal : (DBMSourceTree.data %d).terminal = true := by decide +kernel' % n,
          'theorem node_radius', SIG[0], SIG[1].replace('data 4096 n', 'data 4096 %d' % n), SIG[2], SIG[3], SIG[4][:-6],
          '  := Paid16MatrixCellCertificate.node_radius_of_refinement %d sub 0 sub_valid root_scaled pk pk_ok y hy0 hy1 hc C Z r hf' % n,
          'def newIDs : Finset (Fin 5011) := {%d}' % n,
          'theorem new_terminal (n : Fin 5011) (hn : n ∈ newIDs) : (DBMSourceTree.data n).terminal = true := by',
          '  rw [Finset.mem_singleton.mp hn]; exact terminal',
          'theorem new_radius (n : Fin 5011) (hn : n ∈ newIDs)'] + SIG + [
          '  rw [Finset.mem_singleton.mp hn] at hc ⊢', '  exact node_radius y hy0 hy1 hc C Z r hf',
          'end', 'end ' + ns, '#print axioms %s.new_radius' % ns]
    return '\n'.join(L) + '\n'

