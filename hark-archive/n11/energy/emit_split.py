if __name__ == '__main__':
    sd = os.path.join(HERE, 'split'); names = []; leaves_total = 0; man = []
    for f in sorted(os.listdir(sd), key=lambda s: int(s.split('.')[0])):
        r = json.load(open(os.path.join(sd, f)))
        if r['status'] != 'pass': continue
        n = r['node']; nodes = flatten(r['tree'])
        check_tree(nodes, [[x * 256 for x in row] for row in SP.ctx.tree[n]['db']])
        nm = 'EnergyRefineN%04d' % n; txt = module(n, nodes)
        atomic(os.path.join(OUTD, nm + '.lean'), txt); names.append(nm)
        nl = sum(x['terminal'] for x in nodes); leaves_total += nl
        man.append(dict(module=nm, node=n, tree_nodes=len(nodes), leaves=nl, sha256=hashlib.sha256(txt.encode()).hexdigest()))
    aggs = []
    for ai in range(0, len(names), 10):
        nm = 'EnergyRefineAgg%02d' % (ai // 10 + 1); aggs.append(nm)
        atomic(os.path.join(OUTD, nm + '.lean'), agg_module(nm, names[ai:ai + 10]))
    if aggs:
        atomic(os.path.join(OUTD, 'EnergyRefineAll.lean'), agg_module('EnergyRefineAll', aggs))
        atomic(os.path.join(OUTD, 'EnergyTerminalBatchB13.lean'), B13)
    atomic(os.path.join(HERE, 'lean-wip', 'MANIFEST-refine.json'), json.dumps(dict(nodes=len(names), leaves=leaves_total, modules=man), indent=1))
    print('refined nodes', len(names), 'leaves', leaves_total, 'aggs', len(aggs))
