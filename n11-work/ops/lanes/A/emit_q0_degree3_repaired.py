#!/usr/bin/env python3
"""Generate a lane-local repaired copy of frozen SevenClassQ0Deg3.lean.

The frozen source opens the hub-census namespace (which transitively imports
the ear-count module) without importing either module, and refers to
`ringOnlyTriangles` before opening its defining namespace.  This emitter keeps
every frozen byte after the import block and every declaration body unchanged;
it inserts the missing imports/open only in the generated copy.
"""

from __future__ import annotations

import hashlib
from pathlib import Path


ROOT = Path(__file__).resolve().parents[4]
LEAN = ROOT / "n11-work" / "lean" / "N11Formalization"
SOURCE = LEAN / "SevenClassQ0Deg3.lean"
OUTPUT = LEAN / "SevenClassQ0Deg3Repaired.lean"
EXPECTED_SHA256 = "48d41f5d3a71c41adc3ff0af26f86740b2f4ed82383a037d182aac0f16075b61"

OLD_OPEN = (
    "open ActualQ0OrderedTwoFans ActualBoundaryNineTies ActualHubTriangleCensus\n"
)
NEW_OPEN = (
    "open ActualQ0OrderedTwoFans ActualBoundaryNineTies ActualHubTriangleCensus\n"
    "open ActualRefinementEarCount\n"
)
OLD_IMPORTS = (
    "import N11Formalization.ActualOrderedMetricGraphs\n"
    "import N11Formalization.ActualMetricClassReduction\n"
    "import N11Formalization.MetricAreaRationalCertificate\n"
)
NEW_IMPORTS = (
    "import N11Formalization.ActualHubTriangleCensus\n"
    "import N11Formalization.ActualOrderedMetricGraphs\n"
    "import N11Formalization.ActualMetricClassReduction\n"
    "import N11Formalization.MetricAreaRationalCertificate\n"
)


def main() -> None:
    raw = SOURCE.read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != EXPECTED_SHA256:
        raise SystemExit(f"frozen source hash changed: {digest}")
    text = raw.decode("utf-8")
    if text.count(OLD_IMPORTS) != 1:
        raise SystemExit("expected one exact frozen import block")
    if text.count(OLD_OPEN) != 1:
        raise SystemExit("expected one exact frozen census-open line")
    repaired = text.replace(OLD_IMPORTS, NEW_IMPORTS, 1).replace(
        OLD_OPEN, NEW_OPEN, 1
    )
    prefix = (
        "/-! Generated by `ops/lanes/A/emit_q0_degree3_repaired.py`.\n\n"
        "Frozen source SHA256: "
        f"`{EXPECTED_SHA256}`.  This copy changes only the import/open block;\n"
        "all declarations and proof bodies are byte-for-byte inherited. -/\n"
    )
    OUTPUT.write_text(prefix + repaired, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)} sha256={hashlib.sha256(OUTPUT.read_bytes()).hexdigest()}")
    print(f"frozen_source_sha256={EXPECTED_SHA256}")


if __name__ == "__main__":
    main()
