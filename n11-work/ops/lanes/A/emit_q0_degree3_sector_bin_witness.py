#!/usr/bin/env python3
"""Emit the exact 72 sector-bin argmax witnesses and their peak checks."""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPORT = HERE / "q0-degree3-sector-bins-audit.json"
OUT = HERE.parents[2] / "lean/N11Formalization/SevenClassQ0Deg3SectorBinWitness.lean"

report = json.loads(REPORT.read_text())
rows = report["rows"]
assert len(rows) == 9 and all(len(r["bins"]) == 8 for r in rows)
assert [r["site"] for r in rows] == list(range(9))
assert all([b["bin"] for b in r["bins"]] == list(range(8)) for r in rows)
w = [[b["argmaxK"] for b in r["bins"]] for r in rows]
for i, row in enumerate(w):
    for j, k in enumerate(row):
        assert (0 <= k <= 2048), (i, j, k)
        last = 2048 if j == 7 else 256 * j + 255
        assert 256 * j <= k <= last
        assert k == rows[i]["bins"][j]["argmaxK"]

vec = ",\n".join("  ![" + ", ".join(map(str, row)) + "]" for row in w)
thm_lines = []
refs = []
for i in range(9):
    for j in range(8):
        name = f"sectorBinPeakValid_{i}{j}"
        refs.append(name)
        thm_lines.append(f'''theorem {name} :
    sectorAt {i} (sectorBinWitness {i} {j}).val ≤ sectorPeakAt {i} := by
  norm_num [sectorBinWitness, sectorAt, sectorValue, sectorPeakAt, sectorUpper,
    areaUpper, nodeBin, nodeBinAt, binIndex, mu, lam, nextSite, nodeQ,
    sinHiNLag, sinLoNLag, sinTQ, Finset.sum_range_succ, RatInterval.piHi]
''')
dispatch = " <;>\n    first\n" + "\n".join(f"    | exact {n}" for n in refs)
source = f'''import N11Formalization.SevenClassQ0Deg3SectorBinShape

/-! Lane A: exact 72-bin argmax witnesses.

Generated by `ops/lanes/A/emit_q0_degree3_sector_bin_witness.py` from
`ops/lanes/A/q0-degree3-sector-bins-audit.json` (exact-rational audit).
The 72 peak comparisons are finite checks.  The within-bin increase/decrease
shape remains a separate obligation. -/
set_option autoImplicit false
noncomputable section
namespace N11Formalization.SevenClassQ0Deg3SectorBinWitness

open MetricAreaRationalCertificate
open SevenClassQ0Deg3Bins
open SevenClassQ0Deg3SectorPeak
open SevenClassQ0Deg3SectorBinShape

/-- Exact argmax grid index for each of the 72 row-bin restrictions. -/
def sectorBinWitness : Fin 9 → Fin 8 → Fin 2049 := ![
{vec}]

{''.join(thm_lines)}
theorem sectorBinPeakValid : SectorBinPeakValid sectorBinWitness := by
  intro i j
  fin_cases i <;> fin_cases j{dispatch}

end N11Formalization.SevenClassQ0Deg3SectorBinWitness
#check @N11Formalization.SevenClassQ0Deg3SectorBinWitness.sectorBinPeakValid
#print axioms N11Formalization.SevenClassQ0Deg3SectorBinWitness.sectorBinPeakValid
'''
OUT.write_text(source)
print("witnesses:", w)
print("sha256:", hashlib.sha256(OUT.read_bytes()).hexdigest())
