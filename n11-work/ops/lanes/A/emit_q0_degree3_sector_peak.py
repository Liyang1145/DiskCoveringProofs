#!/usr/bin/env python3
"""Emit the exact sector peak checks for the q0 degree-three area table."""
from __future__ import annotations

import json
from fractions import Fraction
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
SRC = HERE / "q0-degree3-piecewise-8.json"
OUT = ROOT / "n11-work/lean/N11Formalization/SevenClassQ0Deg3SectorPeak.lean"


def main() -> None:
    data = json.loads(SRC.read_text())
    sectors = data["sectors"]
    assert len(sectors) == 9
    assert [row["site"] for row in sectors] == list(range(9))
    assert [row["witnessK"] for row in sectors] == [1024, 1024] + [1536] * 7

    lines = [
        "import N11Formalization.ActualRingLinkBoundaryData",
        "import N11Formalization.SevenClassQ0Deg3UpperTables",
        "",
        "/-! Lane A: exact sector peaks and the sector unimodal reduction.",
        "",
        "Generated by `ops/lanes/A/emit_q0_degree3_sector_peak.py` from the",
        "exact-rational eight-bin audit.  The nine peak comparisons are separate",
        "kernel checks.  The increasing and decreasing shape obligations remain",
        "explicit in `SectorUnimodal`; this module does not assume or hide them. -/",
        "set_option autoImplicit false",
        "noncomputable section",
        "namespace N11Formalization.SevenClassQ0Deg3SectorPeak",
        "",
        "open MetricAreaRationalCertificate",
        "open SevenClassQ0Deg3Bins",
        "open SevenClassQ0Deg3UpperTables",
        "open N11Formalization.ActualRingLinkBoundaryData",
        "",
        "/-- Exact sector peaks from `q0-degree3-piecewise-8.json`. -/",
        "def sectorWitness : Fin 9 → Fin 2049 := ![",
        "  1024, 1024, 1536, 1536, 1536, 1536, 1536, 1536, 1536]",
        "",
        "/-- Six-decimal rational upper enclosures of the audited sector maxima. -/",
        "def sectorPeakAt : Fin 9 → ℚ := ![",
    ]
    for index, row in enumerate(sectors):
        comma = "," if index < 8 else ""
        exact = Fraction(row["max"])
        denominator = 10**6
        numerator = -((-exact.numerator * denominator) // exact.denominator)
        bound = Fraction(numerator, denominator)
        assert exact <= bound < exact + Fraction(1, denominator)
        lines.append(f"  ({numerator}/{denominator}){comma}")
    lines += [
        "]",
        "",
        "def SectorPeakValid (i : Fin 9) : Prop :=",
        "  sectorUpper (mu (nextSite i)) lam",
        "    (nodeQ RatInterval.piHi 2048 (sectorWitness i)) (nodeBin (sectorWitness i)) ≤",
        "      sectorPeakAt i",
        "",
        "/-- A single-peak factorization of a sector row. -/",
        "def SectorIncTo (i : Fin 9) : Prop :=",
        "  ∀ k : Fin 2049, k ≤ sectorWitness i →",
        "    sectorUpper (mu (nextSite i)) lam (nodeQ RatInterval.piHi 2048 k) (nodeBin k) ≤",
        "      sectorUpper (mu (nextSite i)) lam",
        "        (nodeQ RatInterval.piHi 2048 (sectorWitness i))",
        "        (nodeBin (sectorWitness i))",
        "",
        "def SectorDecFrom (i : Fin 9) : Prop :=",
        "  ∀ k : Fin 2049, sectorWitness i ≤ k →",
        "    sectorUpper (mu (nextSite i)) lam (nodeQ RatInterval.piHi 2048 k) (nodeBin k) ≤",
        "      sectorUpper (mu (nextSite i)) lam",
        "        (nodeQ RatInterval.piHi 2048 (sectorWitness i))",
        "        (nodeBin (sectorWitness i))",
        "",
        "def SectorUnimodal : Prop := ∀ i : Fin 9, SectorIncTo i ∧ SectorDecFrom i",
        "",
        "/-- The analytic shape plus the nine exact peaks pays every sector grid check. -/",
        "theorem sectorValid_of_unimodal (hshape : SectorUnimodal)",
        "    (hpeak : ∀ i : Fin 9, SectorPeakValid i) : SectorValid := by",
        "  intro i k",
        "  by_cases hk : k ≤ sectorWitness i",
        "  · exact ((hshape i).1 k hk).trans (hpeak i)",
        "  · exact ((hshape i).2 k (le_of_lt (lt_of_not_ge hk))).trans (hpeak i)",
        "",
    ]
    for i in range(9):
        witness = int(data["sectors"][i]["witnessK"])
        lines += [
            f"theorem sectorPeakValid_{i} : SectorPeakValid {i} := by",
            f"  rw [show sectorWitness {i} = ({witness} : Fin 2049) by decide +kernel]",
            "  norm_num [SectorPeakValid, sectorPeakAt, sectorWitness, sectorUpper,",
            "    areaUpper, nodeBin, nodeBinAt, binIndex, mu, lam, nextSite, nodeQ,",
            "    sinHiNLag, sinLoNLag, sinTQ, Finset.sum_range_succ, RatInterval.piHi,",
            "    Fin.val_ofNat, Fin.val_mk]",
            "",
        ]
    lines += [
        "theorem sectorPeakValid_all : ∀ i : Fin 9, SectorPeakValid i := by",
        "  intro i",
        "  fin_cases i <;>",
        "    first",
    ]
    for i in range(9):
        lines.append(f"    | exact sectorPeakValid_{i}")
    lines += [
        "",
        "/-- All sector obligations reduce to the two explicit shape halves. -/",
        "theorem sectorValid_of_shape (hshape : SectorUnimodal) : SectorValid :=",
        "  sectorValid_of_unimodal hshape sectorPeakValid_all",
        "",
        "end N11Formalization.SevenClassQ0Deg3SectorPeak",
        "#check @N11Formalization.SevenClassQ0Deg3SectorPeak.sectorValid_of_unimodal",
        "#check @N11Formalization.SevenClassQ0Deg3SectorPeak.sectorValid_of_shape",
        "#print axioms N11Formalization.SevenClassQ0Deg3SectorPeak.sectorValid_of_unimodal",
        "#print axioms N11Formalization.SevenClassQ0Deg3SectorPeak.sectorPeakValid_all",
    ]
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
