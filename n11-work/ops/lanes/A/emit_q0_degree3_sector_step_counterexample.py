#!/usr/bin/env python3
"""Emit the exact row-0 counterexample to `SectorAdjacentUnimodal`."""
from __future__ import annotations
import hashlib, json, sys
from fractions import Fraction as F
from pathlib import Path
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import probe_q0_degree3_nodes as probe
REPORT = HERE / "q0-degree3-piecewise-8.json"
AUDIT = HERE / "q0-degree3-sector-steps-audit.json"
OUT = HERE.parents[2] / "lean/N11Formalization/SevenClassQ0Deg3SectorStepCounterexample.lean"

def sector_values():
    _, row = probe.load()
    report = json.loads(REPORT.read_text())
    mu = [probe.mid(x) for x in row["mu"]]
    lam = probe.mid(row["lambda"])
    _, upper = probe.interval(row["pi_interval"])
    qs = [upper * k / probe.N for k in range(probe.N + 1)]
    sines = [probe.sinHi(q) for q in qs]
    node8 = [F(item["node"]) for item in report["bins"]]
    nodes = [node8[min(7, 8 * k // probe.N)] for k in range(probe.N + 1)]
    segment = [(2 * a - probe.sinLo(2 * a)) / 2 for a in node8]
    return [segment[min(7, 8 * k // probe.N)] + probe.R2 * sines[k] / 2
            + 2 * lam * nodes[k] - mu[0] * qs[k] for k in range(probe.N + 1)]

def main():
    values = sector_values()
    row = next(r for r in json.loads(AUDIT.read_text())["rows"] if r["site"] == 0)
    assert row["largestIncFailureK"] == 1022
    assert values[1023] < values[1022]
    assert values[1022] - values[1023] == F(row["largestIncDrop"])
    source = '''import N11Formalization.SevenClassQ0Deg3SectorShape

/-! Lane A: the global adjacent-step sector premise is false.

Generated by `ops/lanes/A/emit_q0_degree3_sector_step_counterexample.py`.
The exact-rational audit's strongest row-0 increasing-step failure is between
indices 1022 and 1023, strictly below witness 1024.  Hence the increasing
premise for row 0, and therefore `SectorAdjacentUnimodal`, is refutable.  The
paid route remains the eight-bin reduction in `SectorBinShape`. -/
set_option autoImplicit false
noncomputable section
namespace N11Formalization.SevenClassQ0Deg3SectorStepCounterexample

open MetricAreaRationalCertificate
open SevenClassQ0Deg3Bins
open SevenClassQ0Deg3UpperTables
open N11Formalization.ActualRingLinkBoundaryData
open N11Formalization.ActualRingDirectionOrder
open N11Formalization.ActualBoundaryCyclicOrder
open SevenClassQ0Deg3SectorPeak
open SevenClassQ0Deg3SectorShape

/-- Row 0 decreases between the audited indices 1022 and 1023. -/
theorem sectorValue_row0_step_down :
    sectorValue 0 ⟨1023, by decide⟩ < sectorValue 0 ⟨1022, by decide⟩ := by
  norm_num [sectorValue, sectorUpper, areaUpper, nodeBin, nodeBinAt, binIndex,
    mu, lam, nextSite, ringSite, nextRing, nodeQ, sinHiNLag, sinLoNLag, sinTQ,
    Finset.sum_range_succ, RatInterval.piHi, Fin.val_ofNat, Fin.val_mk]

/-- The global adjacent-step premise is false already on row 0. -/
theorem not_sectorAdjacentUnimodal : ¬ SectorAdjacentUnimodal := by
  intro h
  have hstep := (h 0).1 ⟨1022, by decide⟩ (by decide +kernel)
  exact (not_le_of_gt sectorValue_row0_step_down) hstep

end N11Formalization.SevenClassQ0Deg3SectorStepCounterexample
#check @N11Formalization.SevenClassQ0Deg3SectorStepCounterexample.sectorValue_row0_step_down
#check @N11Formalization.SevenClassQ0Deg3SectorStepCounterexample.not_sectorAdjacentUnimodal
#print axioms N11Formalization.SevenClassQ0Deg3SectorStepCounterexample.not_sectorAdjacentUnimodal
'''
    OUT.write_text(source)
    print("PASS: row 0 step 1022 -> 1023 is decreasing")
    print("exact drop numerator digits:", len(str(values[1022].numerator - values[1023].numerator)))
    print("wrote", OUT.relative_to(HERE.parents[3]), "sha256", hashlib.sha256(OUT.read_bytes()).hexdigest())

if __name__ == "__main__":
    main()
