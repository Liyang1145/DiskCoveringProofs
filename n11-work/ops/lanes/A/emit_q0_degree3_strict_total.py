        "      norm_num [RatInterval.piLo]",
        "    exact hmul.trans hnum",
        "  have he := edgeMax_sum_le",
        "  have hs := sectorMax_sum_le",
        "  have hei := edge_increment_sum_le",
        "  have hsi := sector_increment_sum_le",
        "  have hpi : (3.14159265358979323846 : ℚ) ≤ RatInterval.piLo := by",
        "    norm_num [RatInterval.piLo]",
        "  have hsum : totalCoeff * RatInterval.piLo +",
