        "  have hconst : -1 + 2134315/1000000 + 8/1000 + 1977695/1000000 + 18/1000 <",
        "      (3.14159265358979323846 : ℚ) := by norm_num",
        "  exact hsum.trans_lt (hconst.trans_le hpi)", "",
        "/-- The canonical 21-edge/9-sector table ledger is strictly below `piLo`. -/",
        "theorem canonicalTableTotal_lt_piLo :",
