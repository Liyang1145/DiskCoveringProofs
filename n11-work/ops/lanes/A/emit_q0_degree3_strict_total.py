        "        (edgeMaxAt i + ((19/50 : ℚ)^2 + |∑ j ∈ tableEdges i, mu j|) *",
        "          RatInterval.piHi / 2048)) +",
        "      (∑ i : Fin 9,",
        "        (sectorMax i + (1 + lam + |mu (nextSite i)|) *",
        "          RatInterval.piHi / 2048)) ≤",
