#!/usr/bin/env python3
"""Emit exact q0 degree-three edge/sector maxima from the audited JSON."""
import json
from pathlib import Path
HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
SRC = HERE / 'q0-degree3-piecewise-8.json'
OUT = ROOT / 'n11-work/lean/N11Formalization/SevenClassQ0Deg3UpperTables.lean'

def main():
    d = json.loads(SRC.read_text())
    edges, sectors = d['edges'], d['sectors']
    assert len(edges) == 21 and len(sectors) == 9
    assert d['N'] == 2048 and d['binCount'] == 8 and d['strictBelowPiLo']
    L = [
        'import N11Formalization.SevenClassQ0Deg3EndpointChecks', '',
        '/-! Lane A: exact rational maxima for the q0 degree-three area table.',
        'Generated by `ops/lanes/A/emit_q0_degree3_upper_tables.py`.  The 21 edge',
        'and 9 sector all-grid inequalities remain explicit indexed premises. -/',
        'set_option autoImplicit false', 'noncomputable section',
        'namespace N11Formalization.SevenClassQ0Deg3UpperTables', '',
        'open MetricAreaRationalCertificate', 'open SevenClassQ0Deg3Bins', '',
        'def mu : Fin 11 → ℚ := ![' + ', '.join(d['mu']) + ']',
        'def lam : ℚ := ' + d['lambda'], '',
        'def tableEdges : Fin 21 → Finset (Fin 11) := ![']
    for i, item in enumerate(edges):
        L.append('  ({' + ', '.join(map(str, item['edge'])) + '} : Finset (Fin 11))' + (',' if i < 20 else ''))
    L += [']', '', 'def edgeMaxAt : Fin 21 → ℚ := ![']
    for i, item in enumerate(edges):
        L.append('  (' + item['max'] + ')' + (',' if i < 20 else ''))
    L += [']', '',
          'def edgeMax (e : Finset (Fin 11)) : ℚ :=',
          '  if h : ∃ i : Fin 21, tableEdges i = e then edgeMaxAt (Classical.choose h) else 0', '',
          'def sectorMax : Fin 9 → ℚ := ![']
    for i, item in enumerate(sectors):
        L.append('  (' + item['max'] + ')' + (',' if i < 8 else ''))
    L += [']', '',
          'def EdgeCheck (i : Fin 21) (k : Fin 2049) : Prop :=',
          '  edgeUpper (∑ j ∈ tableEdges i, mu j) (nodeQ RatInterval.piHi 2048 k) ≤ edgeMaxAt i', '',
          'def SectorCheck (i : Fin 9) (k : Fin 2049) : Prop :=',
          '  sectorUpper (mu (nextSite i)) lam (nodeQ RatInterval.piHi 2048 k) (nodeBin k) ≤ sectorMax i', '',
          'def EdgeValid : Prop := ∀ i k, EdgeCheck i k',
          'def SectorValid : Prop := ∀ i k, SectorCheck i k', '',
          'end N11Formalization.SevenClassQ0Deg3UpperTables',
          '#check @N11Formalization.SevenClassQ0Deg3UpperTables.EdgeValid',
          '#check @N11Formalization.SevenClassQ0Deg3UpperTables.SectorValid']
    OUT.write_text('\n'.join(L) + '\n')
    print(f'wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size} bytes)')

if __name__ == '__main__':
    main()
