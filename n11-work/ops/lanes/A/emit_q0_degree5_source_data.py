#!/usr/bin/env python3
"""Emit exact q0(5,8) source data as a Lean table skeleton.

Only source reconstruction is claimed.  The module defines the exact
121-slot LP vector, its nine named groups, and the 11-face/21-edge graph.
It does not assert factor bounds, a strict total, or an exclusion.
"""
from __future__ import annotations
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
SOURCE = HERE / "q0-degree5-exact-source.json"
OUT = ROOT / "n11-work/lean/N11Formalization/Q0Degree5SourceData.lean"


def q(pair: list[int]) -> str:
    n, d = pair
    if n == 0:
        return "(0 : ℚ)"
    return f"(({n} : ℚ) / {d})"


def array(name: str, vals: list[str]) -> str:
    return f"def {name} : Fin {len(vals)} → ℚ := ![\n  " + ",\n  ".join(vals) + "\n]\n"


def face(f: list[int]) -> str:
    return "({" + ", ".join(map(str, f)) + "} : Finset (Fin 11))"


def main() -> None:
    d = json.loads(SOURCE.read_text())
    assert d["status"] == "PASS_EXACT_DECIMAL_SOURCE_RECONSTRUCTION"
    assert d["coefficient_count"] == 121
    coeffs = d["coefficients"]
    lines = [
        "import N11Formalization.ActualOrderedMetricGraphs",
        "",
        "/-! Exact q0(5,8) source table. Generated by",
        "`ops/lanes/A/emit_q0_degree5_source_data.py` from the hash-bound",
        "reconstruction `q0-degree5-exact-source.json`.  This is source data only;",
        "no factor bound, strict total, or exclusion is asserted. -/",
        "set_option autoImplicit false",
        "noncomputable section",
        "namespace N11Formalization.Q0Degree5SourceData",
        "",
        "open ActualOrderedMetricGraphs",
        "",
    ]
    for name in ("mu", "hub", "side", "radius", "angle_slack", "lambda", "eta", "linear", "closure"):
        g = d["field_groups"][name]
        vals = coeffs[g["start"]:g["start"] + g["size"]]
        lines.append(array(name, [q(v) for v in vals]))
    lines += [
        "def faceAt : Fin 11 → Finset (Fin 11) := ![",
        "  " + ",\n  ".join(face(f) for f in d["lean_graph_faces"]),
        "]\n",
        "def edgeAt : Fin 21 → Finset (Fin 11) := ![",
        "  " + ",\n  ".join(face(e) for e in d["lean_graph_edges"]),
        "]\n",
        "def faceSet : Finset (Finset (Fin 11)) := Finset.univ.image faceAt",
        "def edgeSet : Finset (Finset (Fin 11)) := Finset.univ.image edgeAt\n",
        "theorem faceSet_eq_q0Faces : faceSet = q0Faces 3 := by",
        "  decide +kernel\n",
        "theorem edgeSet_eq_q0Edges : edgeSet = q0Edges 3 := by",
        "  decide +kernel\n",
        "def coefficientCount : Nat := 121",
        "theorem sourceCoefficientCount : coefficientCount = 121 := rfl\n",
        "end N11Formalization.Q0Degree5SourceData",
        "#check @N11Formalization.Q0Degree5SourceData.mu",
        "#check @N11Formalization.Q0Degree5SourceData.faceSet_eq_q0Faces",
        "#check @N11Formalization.Q0Degree5SourceData.edgeSet_eq_q0Edges",
    ]
    OUT.write_text("\n".join(lines) + "\n")
    print(OUT)


if __name__ == "__main__":
    main()
