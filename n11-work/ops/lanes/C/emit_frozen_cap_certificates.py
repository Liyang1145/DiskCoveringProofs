#!/usr/bin/env python3
"""Emit exact Lean data for the seven public frozen-cap exclusions.

This does not assert that any packet is Valid.  It exposes the exact F0/G/y
data and reduces each certificate to a kernel rational inequality; the frozen
identity and arbitrary-row cap hypotheses remain explicit on the theorems.
"""
from fractions import Fraction as Q
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
CERT = HERE / "next512-row-cap-certificates.json"
PROP = ROOT / "evidence-20261028/inputs/paid16-general-next512.json"
OUT = ROOT / "lean/N11Formalization/FrozenCapCertificates.lean"


def rat(text: str) -> str:
    value = Q(text)
    if value.denominator == 1:
        return f"({value.numerator} : ℚ)"
    return f"(({value.numerator} : ℚ) / {value.denominator})"


def vec(values) -> str:
    return "![" + ", ".join(rat(v) for v in values) + "]"


def main() -> None:
    cert_doc = json.loads(CERT.read_text())
    proposal = json.loads(PROP.read_text(encoding="utf-8-sig"))
    records = {r["id"]: r for r in proposal["records"]}
    certs = cert_doc["certificates"]
    if len(certs) != 7 or {c["id"] for c in certs} != {1409, 2337, 2341, 2356, 2360, 2368, 2370}:
        raise AssertionError("stale or unexpected frozen certificate set")
    lines = [
        "import N11Formalization.PaidCellCertificateMCap",
        "",
        "/-! Exact seven-node frozen-cap reductions generated by",
        "`ops/lanes/C/emit_frozen_cap_certificates.py`; no claim of kernel-paid packets. -/",
        "set_option autoImplicit false",
        "namespace N11Formalization.FrozenCapCertificates",
        "open Finset ConvexMinorantCore DBMMinorantDual",
        "noncomputable section",
        "",
    ]
    for cert in certs:
        n = cert["id"]
        rec = records[n]
        lines += [
            f"def F0_{n} : ℚ := {rat(rec['f0Lo'])}",
            f"def G_{n} : Fin 9 → ℚ := {vec(rec['g'])}",
            f"def y_{n} : Fin 9 → ℚ := {vec(cert['weights'])}",
            "",
        ]
    for cert in certs:
        n = cert["id"]
        lines += [
            f"theorem strict_gain_{n} :",
            f"    F0_{n} + ∑ q : Fin 9, y_{n} q *",
            "      endpointLo N11Formalization.FlashCosine.Dq N11Formalization.FlashCosine.DQ (G_"
            f"{n} q) < N11Formalization.FlashCosineLeaf284Bridge.T ^ 2 := by",
            f"  norm_num [F0_{n}, G_{n}, y_{n}, endpointLo, N11Formalization.FlashCosine.Dq,",
            "    N11Formalization.FlashCosine.DQ, N11Formalization.FlashCosineLeaf284Bridge.T,",
            "    N11Formalization.FlashCosine.Lq, N11Formalization.FlashCosine.LQ,",
            "    N11Formalization.RatInterval.piLo, N11Formalization.RatInterval.piHi]",
            "",
            f"theorem excluded_{n} {{m : ℕ}} (p : PaidCellCertificateM.Packet m)",
            "    (hp : PaidCellCertificateM.Valid p)",
            f"    (hf0 : f0Lo (PaidCellCertificateM.W p) (PaidCellCertificateM.slopeQ p)",
            f"      (PaidCellCertificateM.interQ p) = F0_{n})",
            f"    (hg : ∀ q, g (PaidCellCertificateM.W p) (PaidCellCertificateM.slopeQ p) q = G_{n} q)",
            "    (hcap : ∀ a : Fin m,",
            f"      (∑ q : Fin 9, y_{n} q * rowA (p.rowFrom a) (p.rowTo a) q) ≤",
            "        db p.nodeID (p.rowFrom a) (p.rowTo a)) : False :=",
            f"  PaidCellCertificateMCap.not_valid_of_frozen_cap p hp F0_{n} G_{n} y_{n}",
            f"    hf0 hg (by norm_num [y_{n}]) (by norm_num [y_{n}]) hcap",
            f"    (by simpa only using strict_gain_{n})",
            "",
        ]
    lines += ["end", "end N11Formalization.FrozenCapCertificates"]
    for cert in certs:
        n = cert["id"]
        lines += [
            f"#check @N11Formalization.FrozenCapCertificates.excluded_{n}",
            f"#print axioms N11Formalization.FrozenCapCertificates.excluded_{n}",
        ]
    OUT.write_text("\n".join(lines) + "\n")
    print(OUT)
    print("sha256", hashlib.sha256(OUT.read_bytes()).hexdigest().upper())


if __name__ == "__main__":
    main()
