#!/usr/bin/env python3
"""Emit exact weighted row-cap modules for all seven frozen-cap ids."""
from fractions import Fraction as Q
import hashlib
import json
from pathlib import Path

import recheck_next512_rows as common

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
DBM = ROOT / "n11-work/lean/N11Formalization/DBMSourceTreeData.lean"
OUTDIR = ROOT / "n11-work/lean/N11Formalization"
IDS = (1409, 2337, 2341, 2356, 2360, 2368, 2370)


def lean_rat(q: Q) -> str:
    if q.denominator == 1:
        return f"({q.numerator} : ℚ)"
    return f"({q.numerator} : ℚ) / {q.denominator}"


def emit(node: int, db, cert: dict, dbm_sha: str) -> tuple[Path, int, Q]:
    y = [Q(v) for v in cert["weights"]]
    if len(y) != 9 or any(v < 0 for v in y) or sum(y) != 1:
        raise AssertionError(f"node {node}: invalid dual weights")
    slacks = []
    for i in range(10):
        for j in range(10):
            lhs = sum(y[q] * common.row_a(i, j, q) for q in range(9))
            rhs = Q(db[i][j], 4096)
            if lhs > rhs:
                raise AssertionError((node, i, j, lhs, rhs))
            slacks.append(rhs - lhs)
    db_cases = "\n  ".join(
        f"| ⟨{i}, _⟩, ⟨{j}, _⟩ => {lean_rat(Q(db[i][j], 4096))}"
        for i in range(10) for j in range(10))
    ns = f"FrozenCapRowCap{node}"
    leaves = []
    for i in range(10):
        for j in range(10):
            lhs = sum(y[q] * common.row_a(i, j, q) for q in range(9))
            rhs = Q(db[i][j], 4096)
            leaves.append(f'''theorem row_cap_{node}_{i}_{j} :
    {lean_rat(lhs)} ≤ {lean_rat(rhs)} := by
  norm_num''')
    row_lemmas = []
    for i in range(10):
        row_lemmas.append(f'''theorem row_cap_{node}_{i} (j : Fin 10) :
    (∑ q : Fin 9, y_{node} q * rowA {i} j q) ≤ db {i} j := by
  fin_cases j <;> norm_num [rowA, y_{node}, db, Fin.sum_univ_succ]''')
    lines = [
        "import N11Formalization.FrozenCapRationalCore",
        "import Mathlib.Tactic.FinCases",
        "import Mathlib.Tactic.NormNum",
        "",
        f"/-! Exact 100 ordered-pair weighted caps for frozen node {node}.",
        "Generated by `ops/lanes/C/emit_frozen_cap_row_caps.py` from the",
        f"hash-checked `DBMSourceTree.node{node}` matrix. -/",
        "set_option autoImplicit false",
        f"namespace N11Formalization.{ns}",
        "open Finset",
        "open N11Formalization.FrozenCapRationalCore",
        "noncomputable section",
        "",
        "def rowA (i j : Fin 10) (q : Fin 9) : ℚ :=",
        "  (if q.val < j.val then 1 else 0) - (if q.val < i.val then 1 else 0)",
        "",
        "def db : Fin 10 → Fin 10 → ℚ",
        "  " + db_cases,
        "",
        "\n\n".join(leaves),
        "",
        "\n\n".join(row_lemmas),
        "",
        "theorem row_cap (i j : Fin 10) :",
        f"    (∑ q : Fin 9, y_{node} q * rowA i j q) ≤ db i j := by",
        "  fin_cases i",
        *[f"  · exact row_cap_{node}_{i} j" for i in range(10)],
        "",
        "end",
        f"end N11Formalization.{ns}",
        f"#check @N11Formalization.{ns}.row_cap",
        f"#print axioms N11Formalization.{ns}.row_cap",
    ]
    out = OUTDIR / f"{ns}.lean"
    out.write_text("\n".join(lines) + "\n")
    print(out.relative_to(ROOT))
    print("sha256", hashlib.sha256(out.read_bytes()).hexdigest().upper())
    print("dbm_sha256", dbm_sha)
    print("rows_checked 100 min_slack", min(slacks))
    return out, len(slacks), min(slacks)


def main() -> None:
    text = DBM.read_text()
    doc = json.loads((HERE / "next512-row-cap-certificates.json").read_text())
    actual_dbm_sha = hashlib.sha256(DBM.read_bytes()).hexdigest().upper()
    if actual_dbm_sha != doc["dbm_sha256"]:
        raise AssertionError(f"DBM drift: {actual_dbm_sha} != {doc['dbm_sha256']}")
    certs = {c["id"]: c for c in doc["certificates"]}
    if set(certs) != set(IDS) or len(doc["certificates"]) != len(IDS):
        raise AssertionError("stale or unexpected frozen certificate set")
    total = 0
    global_min = None
    for node in IDS:
        db = common.parse_db(text, node)
        _, count, min_slack = emit(node, db, certs[node], actual_dbm_sha)
        total += count
        global_min = min_slack if global_min is None else min(global_min, min_slack)
    print("modules", len(IDS), "rows_checked", total, "global_min_slack", global_min)


if __name__ == "__main__":
    main()
