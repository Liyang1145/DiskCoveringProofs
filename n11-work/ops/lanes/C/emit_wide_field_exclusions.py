#!/usr/bin/env python3
"""Emit exact wide-support exclusion certificates for all seven public residuals.

The earlier four/five-field search maximised the cap-feasible gain and then
emitted the exclusion inequality with the opposite sign.  These witnesses were
instead found by minimising that gain.  Every row cap and the strict `< T^2`
inequality is rechecked with `Fraction` before any Lean is written.
"""
from fractions import Fraction as Q
import hashlib
import json
from pathlib import Path
import sys

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
sys.path.insert(0, str(HERE))
import recheck_next512_rows as common

IDS = (1409, 2337, 2341, 2356, 2360, 2368, 2370)
