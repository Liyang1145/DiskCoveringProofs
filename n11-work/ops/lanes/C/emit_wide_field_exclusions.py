def emit_tree(rows):
    bridges, wrappers = [], []
    for node, _, _, _, _, _ in rows:
        bridges.append(f'''theorem db_eq_tree_{node} : ∀ i j : Fin 10,
    (((N11Formalization.DBMSourceTree.data ({node} : Fin 5011)).db i j : ℚ) / 4096) =
      db_{node} i j := by
  decide +kernel''')
        wrappers.append(f'''theorem excluded_{node}_tree {{m : ℕ}} (p : PaidCellCertificateM.Packet m)
    (hp : PaidCellCertificateM.Valid p) (hnode : p.nodeID = ({node} : Fin 5011))
    (hf0 : f0Lo (PaidCellCertificateM.W p) (PaidCellCertificateM.slopeQ p)
      (PaidCellCertificateM.interQ p) = F0_{node})
    (hg : ∀ q, g (PaidCellCertificateM.W p) (PaidCellCertificateM.slopeQ p) q = G_{node} q) : False := by
  apply PaidCellCertificateMCap.not_valid_of_frozen_cap p hp F0_{node} G_{node} yW_{node}
    hf0 hg nonneg_{node} sum_{node}
  · intro a
    have hrow := row_cap_{node} (p.rowFrom a) (p.rowTo a)
    have hbridge := db_eq_tree_{node} (p.rowFrom a) (p.rowTo a)
    simpa only [hnode, DBMMinorantDual.db, hbridge,
      DBMMinorantDual.rowA, rowA] using hrow
  · simpa only [T, N11Formalization.FlashCosineLeaf284Bridge.T] using strict_gain_{node}''')
    src = '''import N11Formalization.DBMSourceTreeData
import N11Formalization.FrozenCapWideFieldRowCaps
import N11Formalization.PaidCellCertificateMCap

/-! Node-pinned wrappers for the seven wide-support exclusions.  They remain
conditional on the packet's `f0Lo`/`g` identifications, which are not supplied. -/
set_option autoImplicit false
namespace N11Formalization.FrozenCapWideFieldExcludedTree
open Finset ConvexMinorantCore DBMMinorantDual
open FrozenCapRationalCore
open N11Formalization.FrozenCapWideFieldWitnesses
open N11Formalization.FrozenCapWideFieldRowCaps
noncomputable section

''' + "\n\n".join(bridges) + "\n\n" + "\n\n".join(wrappers) + '''

end
end N11Formalization.FrozenCapWideFieldExcludedTree

#check @N11Formalization.FrozenCapWideFieldExcludedTree.excluded_1409_tree
#check @N11Formalization.FrozenCapWideFieldExcludedTree.excluded_2370_tree
'''
    TREE.write_text(src)


def main():
    rows = checked()
    emit_witnesses(rows)
    emit_row_caps(rows)
    emit_tree(rows)
    for path in (WITNESSES, ROW_CAPS, TREE):
        print(path.relative_to(ROOT), hashlib.sha256(path.read_bytes()).hexdigest().upper())
    print("exact_rows", 100 * len(rows), "minimum_cap_slack", [(n, str(s)) for n, _, _, s, _, _ in rows])
    print("strict_gain_margins", [(n, str(m)) for n, _, _, _, m, _ in rows])


if __name__ == "__main__":
    main()
