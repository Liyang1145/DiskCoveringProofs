def check_n18_upper():
    """Cover the unit closed disk with exact rational coordinates and radius."""
    if len(CENTER_NUMERATORS) != 18 or len(set(CENTER_NUMERATORS)) != 18:
        raise ArithmeticError("expected 18 distinct centers")
    if len(RADIUS_DISPLAY.split(".")[1]) != 60 or Fraction(RADIUS_DISPLAY) != Fraction(
        RADIUS_NUMERATOR, CENTER_DENOMINATOR
    ):
        raise ArithmeticError("radius display does not encode the certified radius")
    centers = [(x*DYADIC_SCALE, y*DYADIC_SCALE) for x, y in CENTER_NUMERATORS]
    counts = _replay(centers, CENTER_DENOMINATOR*DYADIC_SCALE,
                     RADIUS_NUMERATOR*DYADIC_SCALE, MAX_DEPTH)
    if (counts["visited"] != 1 + 4*counts["split"] or
        counts["visited"] != counts["outside"] + counts["covered"] + counts["split"]):
        raise ArithmeticError("inconsistent quadtree accounting")
    return {
        "n": 18,
        "status": "certified_upper_only",
        "upper_exact": RADIUS_DISPLAY,
        "upper_rational": str(Fraction(RADIUS_NUMERATOR, CENTER_DENOMINATOR)),
        "center_numerators": [list(p) for p in CENTER_NUMERATORS],
        "center_denominator": CENTER_DENOMINATOR,
        "source": {"url": SOURCE_URL, "commit": SOURCE_COMMIT,
                   "sha256": SOURCE_SHA256, "role": "construction seed only"},
        "checked": counts,
    }


if __name__ == "__main__":
    print(json.dumps(check_n18_upper(), indent=2))
